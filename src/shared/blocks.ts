export function getItemDef(id: AnyItemId): ItemDefinition | undefined {
  return ITEM_DEFINITIONS[id];
}

export function isBlockSolid(id: BlockId): boolean {
  if (id === BlockId.Air) return false;
  const def = ITEM_DEFINITIONS[id];
  return Boolean(def?.solid);
}

export function isBlockTransparent(id: BlockId): boolean {
  if (id === BlockId.Air) return true;
  const def = ITEM_DEFINITIONS[id];
  return Boolean(def?.transparent);
}

